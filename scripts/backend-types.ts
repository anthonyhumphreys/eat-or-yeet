import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

// Keep Wrangler's bindings in a module. Its ambient runtime types conflict with
// Next.js DOM types when both runtimes share one TypeScript project.
const filename = ".wrangler/bindings.generated.d.ts";
mkdirSync(".wrangler", { recursive: true });
execFileSync("pnpm", ["exec", "wrangler", "types", filename, "--env-interface", "CloudflareBindings", "--include-runtime", "false"], { stdio: "inherit" });
const source = readFileSync(filename, "utf8");
const declaration = source.match(/interface __BaseEnv_CloudflareBindings\s*\{[^}]*\}/)?.[0]?.replace("__BaseEnv_CloudflareBindings", "CloudflareBindings");
if (!declaration) throw new Error("Wrangler did not generate its binding interface");
writeFileSync("backend/bindings.d.ts", `// Generated by pnpm backend:types. Do not edit.\nimport type { D1Database, R2Bucket, Queue, Fetcher } from "@cloudflare/workers-types";\nexport ${declaration}\n`);
